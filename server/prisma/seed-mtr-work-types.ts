async function main() {
  console.log('Начинаем наполнение справочника mtr_work_types...');

  // Загружаем существующие записи
  const existing = await prisma.mtrWorkType.findMany({ select: { name: true } });
  const existingSet = new Set(existing.map(e => e.name.trim().toLowerCase()));

  let created = 0;
  let skipped = 0;

  for (const wt of workTypes) {
    const normalizedName = wt.name.trim();
    const key = normalizedName.toLowerCase();

    if (existingSet.has(key)) {
      skipped++;
      continue;
    }

    await prisma.mtrWorkType.create({
      data: {
        name: normalizedName,
        category: wt.category,
        isActive: true,
      },
    });

    existingSet.add(key);
    created++;
  }

  console.log(`Готово! Создано: ${created}, пропущено (дубликаты): ${skipped}`);
  console.log(`Всего в справочнике: ${existing.length + created} записей`);
}

main()
  .catch((e) => {
    console.error('Ошибка при наполнении справочника:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
